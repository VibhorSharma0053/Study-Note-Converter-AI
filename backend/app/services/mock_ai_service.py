from app.models.responses import (
    CodeSnippet,
    Concept,
    InterviewQuestion,
    ParseResponse,
    PracticeQuestion,
)
from app.services.ai_service import AIService


class MockAIService(AIService):
    """
    Temporary AI service used before a real provider is integrated.

    It follows the exact same interface as GeminiService will use later.
    This lets us test the router and frontend without API keys or API costs.
    """

    async def parse_transcript(self, transcript: str) -> ParseResponse:
        word_count = len(transcript.split())

        return ParseResponse(
            title="Mock Study Notes",
            subject="Development Mode",
            summary=(
                "This response was generated by the local MockAIService. "
                f"The submitted transcript contains {len(transcript)} characters "
                f"and approximately {word_count} words."
            ),
            concepts=[
                Concept(
                    topic="Development",
                    title="Mock AI Service",
                    definition=(
                        "A mock AI service returns predictable test data without "
                        "calling a real AI provider."
                    ),
                    example=(
                        "It lets the frontend dashboard be developed before "
                        "a Gemini, OpenAI, or Ollama integration exists."
                    ),
                )
            ],
            code_snippets=[
                CodeSnippet(
                    title="Mock Service Example",
                    language="python",
                    code='print("Mock AI response")',
                    explanation=(
                        "This placeholder code confirms that code snippets can "
                        "flow through the complete application."
                    ),
                )
            ],
            interview_questions=[
                InterviewQuestion(
                    question="Why use an AI service abstraction?",
                    answer=(
                        "It decouples the application from a specific LLM provider, "
                        "making Gemini, OpenAI, or Ollama replaceable."
                    ),
                    explanation=(
                        "The router depends on the shared AIService interface rather "
                        "than a provider SDK."
                    ),
                    difficulty="medium",
                )
            ],
            practice_questions=[
                PracticeQuestion(
                    question="Which layer should hold an LLM API key?",
                    answer="The backend",
                    question_type="mcq",
                    options=[
                        "The React frontend",
                        "The backend",
                        "The browser local storage",
                        "The public GitHub repository",
                    ],
                    difficulty="easy",
                )
            ],
            important_points=[
                "Treat transcripts as untrusted input.",
                "Treat LLM output as untrusted external data.",
                "Use a low temperature for reliable extraction tasks.",
            ],
        )